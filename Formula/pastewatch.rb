  sha256 "325b3492c5025e64c978f64f39cfb89c7c44587de035d5440f59b0d1d39ae83e"

  def install
    bin.install "pastewatch-cli"
  end

  test do
    assert_match "pastewatch-cli", shell_output("#{bin}/pastewatch-cli version")
  end
end
